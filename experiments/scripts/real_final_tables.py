"""Produce the §V real-data tables from scratch, on the current population.

WHY THIS EXISTS. Every number in the manuscript's §V real-data tables has, until now,
been produced by an ad-hoc script under /tmp and pasted into the .tex. The numbers
could be reproduced, but nothing in the repository said how -- `git grep 95.0316` had
zero hits. This script is the recipe: it runs both matchers at their stated operating
points and evaluates them with the canonical metric definitions, so a table can be
regenerated by one command rather than by remembering which temp file was which.

THE TWO OPERATING POINTS, both taken from the manuscript's own text:

  CaMM  -- k_search = 0 with delta_road = 300 m, i.e. the SAME fixed 300 m disk the
           baseline searches, so the comparison isolates the observation model rather
           than the search; elliptical covariance, Mahalanobis projection, direction
           consistency with one-sided von Mises (c = 0.36, gap guard 2 s), no PHMI
           grouping (phmi = 0), and the map-registration term
           map_error_sigma = 10.6 m = sqrt(10^2 + 3.5^2).
           This is ablation-ladder row 5 of data/archive_20260922/stair/run2.py,
           which EXPERIMENT_DESIGN.md registers as "the paper's model". The
           HPL-adaptive disk (k_search = 1, delta_road = 13.5 m, phmi = 1e-5) is
           row 7 and belongs to paper 2.
  FMM   -- r = 300 m, gps_error = 100 m, reverse_tolerance 0.1, scored with its own
           native Viterbi score delta_t / sum_j delta_t(j) (tw_use_viterbi = true).

Both are run on the same input table and evaluated against the same ground truth.
An epoch is evaluable when it has a labelled ground-truth edge: `gt_edge in
{'0','-1',''}` and trajectory 12 are dropped, which is the population policy
`aligned.csv` already encodes and which `verify_paper_numbers.py` implements.

The population is whatever the current `aligned.csv` says. It moved from 13,123 to
13,069 when the two missing-road windows on Traj 11 were marked non-evaluable
(`mark_missing_road_gt.py`); this script prints the count it used so a stale table is
never mistaken for a current one.

Outputs: data/archive_20260928/final/{cmm.csv, fmm.csv} and a printed table.
Usage: python3 experiments/scripts/real_final_tables.py
"""
