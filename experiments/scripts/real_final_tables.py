def _config(name, out, **subs):
    """Load a committed config and redirect its input and output paths.

    The settings live in input/config/paper1_*.xml rather than here, so that the
    configuration behind Section V's tables is a tracked artefact with its rationale
    beside it (review item R8) and so that there is exactly one copy of it. This
    function only substitutes paths, and asserts that it did.
    """
    text = (CFG_DIR / name).read_text()
    before = text
    text = re.sub(r'<file>data/real_vehicle/[^<]*</file>',
                  f'<file>{BASE / GPS}</file>', text, count=1)
    assert text != before, f'{name}: input path not substituted'
    before = text
    text = re.sub(r'<file>data/archive_[^<]*</file>', f'<file>{out}</file>', text, count=1)
    assert text != before, f'{name}: output path not substituted'
    if 'viterbi' in subs:
        before = text
        text = re.sub(r'<tw_use_viterbi>(true|false)</tw_use_viterbi>',
                      f'<tw_use_viterbi>{subs["viterbi"]}</tw_use_viterbi>', text, count=1)
        assert text != before, f'{name}: tw_use_viterbi not substituted'
    return text



def load_gt():
    """(id, norm_ts) -> (gt_edge, gt_x, gt_y) for the evaluable epochs, plus the
    seq -> timestamp map the FMM join needs.

    THE TWO MATCHERS NEED DIFFERENT JOIN KEYS, and getting this wrong fails
    silently rather than loudly. This is verify_paper_numbers.py's rule, restated
    here because this script does not go through that file's load_mr:

      * CaMM's `timestamp` is unique per epoch but its `seq` is NOT -- the matcher
        splits trajectories and seq restarts at 0 while the timestamps keep
        running (measured on this run: trajectory 11 emits 2,695 rows whose seq
        stops at 1,239). Join CaMM on the timestamp.
      * FMM's `timestamp` is not per-epoch at all -- trajectory 11 has 2,696 rows
        carrying 25 distinct values -- so a timestamp join keeps 104 of 16,155
        epochs and still prints a plausible table. FMM's `seq` is a unique 0-based
        index into the trajectory IT WAS GIVEN, i.e. into the input table's rows
        sorted by timestamp, so resolve it through that map and not through
        aligned.csv -- see the block in load_gt that builds it.

    A third option looks right and is not: `seq` joins both run outputs to
    aligned.csv with no misses at all, but for CaMM those are collisions, not
    correspondences -- the sub-segment counter lands on epochs that merely happen
    to share the same index. That join scored CaMM at 77.65 % against a true
    98.07 % on the 13,069-epoch population.
    """
    gt, ts_by_seq = {}, {}
    # seq -> timestamp for FMM comes from the INPUT TABLE, not from aligned.csv.
    # FMM's `seq` is a 0-based index into the trajectory it was given, and its own
    # timestamp column is not per-epoch, so this map is the only join it has. It
    # must be built from the file FMM actually read: aligned.csv enumerates the
    # union of four sources, and once that union contains epochs the input table
    # does not (11 of them did, from 2026-09-28), uni_seq and seq stop agreeing
    # and every later epoch of a trajectory is joined to the wrong label --
    # measured: FMM scored 93.23 % instead of 95.42 %, with a 27.6 m mean position
    # error instead of 6.0 m, and nothing in the output said anything was wrong.
    per_traj = defaultdict(list)
    with open(BASE / GPS, newline='') as f:
        for r in csv.DictReader(f, delimiter=';'):
            per_traj[r['id'].strip()].append(v.norm_ts(r['timestamp']))
    for tid, stamps in per_traj.items():
        for i, ts in enumerate(sorted(stamps)):
            ts_by_seq[(tid, str(i))] = ts
    with open(ALIGNED, newline='') as f:
        for r in csv.DictReader(f, delimiter=';'):
            tid = r['id'].strip()
            if tid in v.EXCLUDE_TRAJ:
                continue
            e = r['gt_edge'].strip()
            if e in ('0', '-1', ''):
                continue
            try:
                x, y = float(r['gt_x']), float(r['gt_y'])
            except (ValueError, KeyError):
                x = y = float('nan')
            gt[(tid, v.norm_ts(r['timestamp']))] = (e, x, y)
    return gt, ts_by_seq


def load_run(path, ts_by_seq=None):
    """Key a matcher output by (id, norm_ts). Pass ts_by_seq to resolve FMM's seq."""
    out = {}
    with open(path, newline='') as f:
        for r in csv.DictReader(f, delimiter=';'):
            tid = r['id'].strip()
            if ts_by_seq is None:
                key = (tid, v.norm_ts(r['timestamp']))
            else:
                key = (tid, ts_by_seq.get((tid, r['seq'].strip())))
                if key[1] is None:
                    continue
            out[key] = r
    return out


def _pgeom_xy(r):
    """First coordinate of pgeom, which is the matched position of the epoch."""
    s = r.get('pgeom', '')
    i, j = s.find('('), s.find(')')
    if i < 0 or j < 0:
        return None
    parts = s[i + 1:j].split()
    if len(parts) < 2:
        return None
    try:
        return float(parts[0].rstrip(',')), float(parts[1].rstrip(','))
    except ValueError:
        return None


def _n_candidates(r):
    s = r.get('candidates', '')
    # "(lon,lat,w),(lon,lat,w)" -- one weight per candidate. Count the commas at
    # depth 2 by counting the ')' that close a triple.
    if not s:
        # a bare count is also accepted
        try:
            return int(float(s))
        except ValueError:
            return 0
    return s.count('),(') + 1 if '(' in s else 0


def mce(confs, corrects, nbins=10):
    confs, corrects = np.asarray(confs), np.asarray(corrects)
    edges = np.linspace(0.0, 1.0, nbins + 1)
    worst = 0.0
    for b in range(nbins):
        lo, hi = edges[b], edges[b + 1]
        m = (confs > lo) & (confs <= hi) if b else (confs >= lo) & (confs <= hi)
        if m.sum() == 0:
            continue
        worst = max(worst, abs(corrects[m].mean() - confs[m].mean()))
    return worst


def _pairs(run_path, gt, score_col, ts_by_seq=None):
    """Aligned (label, score) arrays plus the per-epoch quantities that are not
    scores. Split out of evaluate() so the binning study can reuse the same join
    and the same score extraction rather than re-deriving them."""
    run = load_run(run_path, ts_by_seq)
    n = ok = 0
    labels, scores = [], []
    errs, cands = [], []
    per_traj = {}
    for key, (gt_edge, gx, gy) in gt.items():
        r = run.get(key)
        if r is None:
            continue
        n += 1
        correct = v.is_edge_match(r['cpath'].strip(), gt_edge)
        ok += int(correct)
        tid = key[0]
        a, b = per_traj.get(tid, (0, 0))
        per_traj[tid] = (a + 1, b + int(correct))
        try:
            s = float(r[score_col])
        except (ValueError, KeyError):
            s = None
        if s is not None and s > -900.0:
            labels.append(1.0 if correct else 0.0)
            scores.append(s)
        p = _pgeom_xy(r)
        if p and gx == gx and gy == gy:
            errs.append(v.haversine_m(p[0], p[1], gx, gy))
        cands.append(_n_candidates(r))
    return (n, ok, np.array(labels), np.array(scores), errs, cands, per_traj)


def evaluate(run_path, gt, score_col, ts_by_seq=None):
    n, ok, labels, scores, errs, cands, per_traj = _pairs(
        run_path, gt, score_col, ts_by_seq)
    p_bar = labels.mean()
    brier = float(((scores - labels) ** 2).mean())
    return dict(
        n=n, acc=100.0 * ok / n,
        err=float(np.mean(errs)), p95=float(np.percentile(errs, 95)),
        cand=float(np.mean(cands)),
        ece=v.ece(scores, labels), mce=mce(scores, labels),
        brier=brier, bss=1 - brier / (p_bar * (1 - p_bar)),
        auc=v.auc(labels, scores),
        sep=float(scores[labels == 1].mean() - scores[labels == 0].mean()),
        mean_tw=float(scores.mean()),
        sat=100.0 * float((scores >= 1.0).mean()),
        distinct=len(np.unique(scores)),
        per_traj={k: (m, 100.0 * c / m) for k, (m, c) in sorted(per_traj.items())},
        # The aligned arrays themselves, so a caller that needs a metric this function
        # does not compute (the log score, a bootstrap replicate, a sub-population ECE)
        # reuses the same join and the same score extraction instead of re-deriving them.
        labels=labels, scores=scores,
    )


def terciles(run_path, gt, score_col, ts_by_seq=None):
    """ECE by position within the trajectory, pooled over trajectories.

    The axis is within-trajectory position, not global row order: each trajectory is
    cut into thirds by its own evaluable epochs and the thirds are then pooled. Cutting
    the pooled rows globally instead would put whole trajectories into one third and
    measure which route was driven rather than where in it, which is a different and
    much larger effect on this data."""
    from collections import defaultdict
    run = load_run(run_path, ts_by_seq)
    by_id = defaultdict(list)
    for key, (gt_edge, _, _) in gt.items():
        r = run.get(key)
        if r is not None:
            by_id[key[0]].append((key[1], r, gt_edge))
    out = []
    for t in range(3):
        lab, sc = [], []
        for rows in by_id.values():
            rows.sort(key=lambda x: x[0])
            lo, hi = int(t * len(rows) / 3), int((t + 1) * len(rows) / 3)
            for _, r, gt_edge in rows[lo:hi]:
                try:
                    s = float(r[score_col])
                except (ValueError, KeyError):
                    continue
                if s <= -900.0:
                    continue
                lab.append(1.0 if v.is_edge_match(r['cpath'].strip(), gt_edge) else 0.0)
                sc.append(s)
        lab, sc = np.array(lab), np.array(sc)
        out.append(dict(n=len(sc), acc=100.0 * lab.mean(), ece=v.ece(sc, lab)))
    return out


def robustness(labels, scores):
    """The two checks that belong beside an equal-width ECE.

    Bin-count sensitivity: if the ordering of the arms moves with B, the table is
    reporting the binning rather than the scores. Equal-mass binning: well defined
    only when the score has enough distinct values to fill the bins, which is the
    same saturation that the audit is about -- so its failure here is a finding,
    not a missing robustness check, and it is reported as such.
    """
    eces = [v.ece(scores, labels, n=B) for B in (10, 15, 20)]
    order = np.argsort(scores)
    s_sorted = scores[order]
    # equal-mass edges; ties inside a bin make the quantiles collapse, which is
    # exactly what the count of non-empty bins measures.
    edges = np.quantile(s_sorted, np.linspace(0, 1, 11))
    edges[0], edges[-1] = -np.inf, np.inf
    nonempty = 0
    for b in range(10):
        m = (scores > edges[b]) & (scores <= edges[b + 1])
        if m.sum():
            nonempty += 1
    return dict(ece_b10=eces[0], ece_b15=eces[1], ece_b20=eces[2],
                distinct=len(np.unique(scores)), nonempty_eqmass=nonempty)


def main():
    OUTDIR.mkdir(parents=True, exist_ok=True)
    gt, ts_by_seq = load_gt()
    print(f'evaluable epochs: {len(gt)}\n')

    runs = {}
    # Four runs give the 2x3 grid of estimators. `cmm` and `fmm` each write TWO of the
    # three columns (the score selected by tw_use_viterbi, plus the smoother's, which
    # always uses the forward recursion), so the proposed matcher's Viterbi score needs
    # its own run -- tw_use_viterbi is a config key, not an output column. The path is
    # the same in both, because the key changes only which recursion is reported, so the
    # three estimators are read off one decoded path and differ only in evidence set.
    for name, tmpl, extra in (('cmm', CMM_CONFIG, {}),
                              ('cmm_viterbi', CMM_CONFIG, {'viterbi': 'true'}),
                              ('fmm', 'paper1_fmm_baseline.xml', {}),
                              ('fmm_post', 'paper1_fmm_baseline.xml', {'viterbi': 'false'})):
        out = OUTDIR / f'{name}.csv'
        with tempfile.NamedTemporaryFile(suffix='.xml', delete=False, mode='w') as fh:
            fh.write(_config(tmpl, out, **extra))
            cfg = fh.name
        log = OUTDIR / f'{name}.log'
        with open(log, 'w') as lf:
            r = subprocess.run([str(BASE / 'build' / ('cmm' if name == 'cmm' else 'fmm')), cfg],
                               cwd=BASE, stdout=lf, stderr=subprocess.STDOUT)
        Path(cfg).unlink()
        if r.returncode != 0:
            print(f'{name}: RUN FAILED (exit {r.returncode}); see {log}')
            return 1
        runs[name] = out
        print(f'{name}: {sum(1 for _ in open(out)) - 1} rows -> {out}')

    arms = [('CaMM (smoothed)', 'cmm', 'trustworthiness_smoothed'),
            ('CaMM (filtering)', 'cmm', 'trustworthiness'),
            ('FMM baseline', 'fmm', 'trustworthiness'),
            ('FMM posterior', 'fmm_post', 'trustworthiness')]
    # CaMM joins on its timestamp; FMM only has a usable seq, so it resolves
    # seq -> timestamp through aligned.csv. See load_gt.
    res = {lab: evaluate(runs[f], gt, c, None if f.startswith('cmm') else ts_by_seq)
           for lab, f, c in arms}

    w = 26
    hdr = f"{'metric':<{w}}" + ''.join(f'{lab:>18}' for lab, _, _ in arms)
    print('\n' + hdr)
    print('-' * len(hdr))
    rows = [
        ('Segment accuracy (%)', 'acc', '{:.2f}'),
        ('Mean position error (m)', 'err', '{:.2f}'),
        ('Position error P95 (m)', 'p95', '{:.2f}'),
        ('Mean candidates / epoch', 'cand', '{:.2f}'),
        ('ECE', 'ece', '{:.4f}'),
        ('MCE', 'mce', '{:.4f}'),
        ('Brier', 'brier', '{:.4f}'),
        ('Brier skill score', 'bss', '{:+.3f}'),
        ('ROC AUC', 'auc', '{:.4f}'),
        ('TW separation', 'sep', '{:.4f}'),
        ('Mean TW', 'mean_tw', '{:.4f}'),
        ('Epochs at TW = 1.000 (%)', 'sat', '{:.1f}'),
        ('Evaluable epochs', 'n', '{:d}'),
    ]
    for label, key, fmt in rows:
        print(f'{label:<{w}}' + ''.join(f'{fmt.format(res[l][key]):>18}' for l, _, _ in arms))

    print('\nper-trajectory accuracy (%)')
    tids = sorted({t for l in res for t in res[l]['per_traj']})
    print(f"{'traj':<8}{'epochs':>8}" + ''.join(f'{l:>18}' for l, _, _ in arms))
    for t in tids:
        m = res[arms[0][0]]['per_traj'].get(t, (0, float('nan')))[0]
        print(f'{t:<8}{m:>8}' + ''.join(
            f"{res[l]['per_traj'][t][1]:>18.2f}" if t in res[l]['per_traj'] else f"{'--':>18}"
            for l, _, _ in arms))
    print(f"{'All':<8}{res[arms[0][0]]['n']:>8}" + ''.join(
        f"{res[l]['acc']:>18.2f}" for l, _, _ in arms))

    print('\nrobustness of the ECE (bin-count sensitivity and equal-mass binning)')
    head = f"{'arm':<22}{'B=10':>9}{'B=15':>9}{'B=20':>9}{'distinct':>10}{'=1.000':>9}{'eq-mass bins':>14}"
    print(head)
    for lab, f, c in arms:
        _, _, labels, scores, _, _, _ = _pairs(
            runs[f], gt, c, None if f.startswith('cmm') else ts_by_seq)
        rb = robustness(labels, scores)
        sat = 100.0 * float((scores >= 1.0).mean())
        print(f"{lab:<22}{rb['ece_b10']:>9.4f}{rb['ece_b15']:>9.4f}{rb['ece_b20']:>9.4f}"
              f"{rb['distinct']:>10}{sat:>8.1f}%{rb['nonempty_eqmass']:>14}")
    print('\nECE by position within the trajectory (thirds of each trajectory, pooled)')
    print(f"{'arm':<22}{'third 1 acc%':>14}{'ECE':>9}{'third 2 acc%':>14}{'ECE':>9}"
          f"{'third 3 acc%':>14}{'ECE':>9}")
    for lab, f, c in (arms[0], arms[1]):
        tc = terciles(runs[f], gt, c)
        print(f'{lab:<22}' + ''.join(
            f"{t['acc']:>14.1f}{t['ece']:>9.4f}" for t in tc))
    return 0


if __name__ == '__main__':
    sys.exit(main())
